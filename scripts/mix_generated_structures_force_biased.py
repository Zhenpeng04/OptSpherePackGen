"""Mix two generated sphere packings in a 3 x 3 x 6 um periodic box.

The script reads the real-unit CSV files generated by SpherePackGen, keeps all
particle radii, randomly mixes the two species, and re-packs them with a
rectangular-box adaptation of the project's force_biased dense-packing method.

Run from the repository root:

    python scripts/mix_generated_structures_force_biased.py

Use --dry-run to only inspect the imported particle counts and target volume
fraction without generating a new packing.
"""

